/*
 * Generates src/styles/theme-colors.css: RGB-channel CSS variables for every
 * Tailwind color scale the app uses, with a light set (Tailwind defaults) and a
 * dark set derived from the GameDay dark palette (navy surfaces #0b1326/#171f33,
 * light text #dae2fd). tailwind.config.js points each scale at these variables,
 * so existing classes like `bg-slate-50`, `text-slate-900` or `bg-orange-50`
 * adapt to dark mode without touching every component.
 *
 * Run: node scripts/generate-theme-colors.cjs
 */
const fs = require('fs');
const path = require('path');
const colors = require('tailwindcss/colors');

const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const HUES = ['red', 'orange', 'amber', 'yellow', 'green', 'emerald', 'teal', 'blue', 'indigo', 'purple', 'pink'];

const hexToRgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16));
};
const mix = (a, b, t) => a.map((v, i) => Math.round(v * t + b[i] * (1 - t)));
const ch = (rgb) => rgb.join(' ');

// Dark neutral scale: low numbers become navy surfaces, high numbers light text.
const DARK_NEUTRAL = {
  50: '#0b1326',  // page background (surface)
  100: '#222a3d', // chips / inset panels (surface-container-high)
  200: '#2d3449', // dividers, skeletons (surface-variant)
  300: '#3a4259',
  400: '#7c86a2',
  500: '#9aa4bf',
  600: '#b6bfd8',
  700: '#c9d1e9',
  800: '#d3dbf5',
  900: '#dae2fd', // primary text (on-surface)
  950: '#eef2ff',
};
const CARD_DARK = hexToRgb('#171f33');

let light = [];
let dark = [];

for (const name of ['slate', 'gray']) {
  for (const s of SHADES) {
    light.push(`--c-${name}-${s}: ${ch(hexToRgb(colors[name][s]))};`);
    dark.push(`--c-${name}-${s}: ${ch(hexToRgb(DARK_NEUTRAL[s]))};`);
  }
}

for (const hue of HUES) {
  const p = Object.fromEntries(SHADES.map(s => [s, hexToRgb(colors[hue][s])]));
  const darkScale = {
    // tints used as backgrounds become translucent-looking tints on navy
    50: mix(p[500], CARD_DARK, 0.14),
    100: mix(p[500], CARD_DARK, 0.22),
    200: mix(p[500], CARD_DARK, 0.32),
    300: mix(p[400], CARD_DARK, 0.5),
    // solid shades stay recognizable for buttons/badges with white text
    400: p[400],
    500: p[500],
    600: p[500],
    // deep shades used for text flip to light shades for contrast
    700: p[300],
    800: p[200],
    900: p[100],
    950: p[50],
  };
  for (const s of SHADES) {
    light.push(`--c-${hue}-${s}: ${ch(p[s])};`);
    dark.push(`--c-${hue}-${s}: ${ch(darkScale[s])};`);
  }
}

const css = `/* AUTO-GENERATED by scripts/generate-theme-colors.cjs. Do not edit by hand. */
:root {
  ${light.join('\n  ')}
}

.dark {
  ${dark.join('\n  ')}
}
`;

const out = path.join(__dirname, '..', 'src', 'styles', 'theme-colors.css');
fs.writeFileSync(out, css);
console.log(`Wrote ${out}`);
module.exports = { HUES, SHADES };
